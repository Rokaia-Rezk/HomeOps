URGENT_MODS = [" بسرعة", " ضروري", " حالا", " ينفع حد ييجي دلوقتي", " الحقوني"]
CALM_MODS = [" مش مستعجل", " في اي وقت الاسبوع الجاي", " براحتكم", " لما تفضوا"]

def typo(s):
    if len(s) < 6 or random.random() > 0.15: return s
    i = random.randrange(1, len(s) - 1)
    r = random.random()
    if r < 0.4: return s[:i] + s[i+1:]                       # حذف حرف
    if r < 0.7: return s.replace("ة", "ه").replace("ي", "ى", 1)
    return s[:i] + s[i] + s[i:]                              # تكرار حرف

def make(problem, prio):
    s = random.choice(PREFIX) + problem + random.choice(SUFFIX)
    # عبارات الاستعجال ترفع (عادي -> عاجل) بس ما بتغيرش الطوارئ
    if random.random() < 0.15:
        if prio == "normal" and random.random() < 0.5:
            s += random.choice(URGENT_MODS); prio = "urgent"
        elif prio == "normal":
            s += random.choice(CALM_MODS)
    return typo(s), prio

